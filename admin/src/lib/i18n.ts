export type Key = keyof typeof dict.ja

export const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: 'ja', setLang: () => {} })

export function useT() {
  const { lang } = useContext(LangContext)
  return (key: Key): string => dict[lang][key] ?? dict.ja[key] ?? key
}

export function useLang() {
  return useContext(LangContext)
}

export function initialLang(): Lang {
  try {
    const stored = localStorage.getItem('sokuto:lang')
    if (stored === 'ja' || stored === 'en') return stored
  } catch {
    /* ignore */
  }
  return navigator.language.startsWith('ja') ? 'ja' : 'en'
}
